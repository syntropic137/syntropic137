#!/usr/bin/env python3
"""Generate the docker-socket-proxy haproxy template (#1398, #1806).

The proxy image (tecnativa/docker-socket-proxy) filters Docker API calls on
method and path. Syntropic137 needs four additions to its stock policy:

- inspect (GET) and release (DELETE) of retained capture volumes, by exact
  ``syn-capture-<64 hex>`` name only (#1398);
- deny of every way to NAME an image (load, tag, import) ahead of the upstream
  allows: the create guard's image allowlist is a name check (#1806);
- container create and exec routed to ``docker-create-guard``, which refuses
  privileged / host-access HostConfig shapes (#1806);
- the ``docker-create-guard`` backend those routes target.

This used to be an inline sh+awk rewrite in each compose file's entrypoint,
run at every container start. It could not be tested or checked without
running it, and a restart re-patched its own output. Now the patched template
is a committed, reviewable file generated here from a committed copy of the
pinned image's own template, and compose mounts it read-only.

WHY A TEMPLATE AND NOT haproxy.cfg. The image's stock entrypoint renders
``haproxy.cfg.template`` into ``haproxy.cfg`` at every start, substituting
``${BIND_CONFIG}`` from ``DISABLE_IPV6``. Every other knob (``POST``,
``CONTAINERS``, ...) is read by haproxy itself at runtime via ``env()``, so it
needs no templating at all. Mounting our file over the template keeps that one
substitution where upstream does it, so ``DISABLE_IPV6`` still works and the
stock entrypoint runs unmodified. The generator therefore leaves
``${BIND_CONFIG}``, ``${LOG_LEVEL}`` and ``$SOCKET_PATH`` untouched.

Usage:
    uv run python scripts/docker_socket_proxy_config.py            # write
    uv run python scripts/docker_socket_proxy_config.py --check    # drift (CI)
    uv run python scripts/docker_socket_proxy_config.py --validate # needs docker:
        the committed upstream copy still equals the pinned image's template,
        and the generated file passes `haproxy -c` inside that image.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

import yaml

PROJECT_ROOT = Path(__file__).resolve().parent.parent
UPSTREAM_TEMPLATE = (
    PROJECT_ROOT / "docker" / "docker-socket-proxy" / "upstream-haproxy.cfg.template"
)
OUTPUT_FILE = PROJECT_ROOT / "docker" / "generated" / "docker-socket-proxy.haproxy.cfg.template"
BASE_COMPOSE = PROJECT_ROOT / "docker" / "docker-compose.yaml"

# Where the image's entrypoint reads the template and writes the config.
IMAGE_TEMPLATE_PATH = "/usr/local/etc/haproxy/haproxy.cfg.template"
IMAGE_CONFIG_PATH = "/usr/local/etc/haproxy/haproxy.cfg"

HEADER = """\
# =============================================================================
# GENERATED by scripts/docker_socket_proxy_config.py -- do not edit by hand.
# Regenerate: just gen-compose. Source: docker/docker-socket-proxy/
# upstream-haproxy.cfg.template (the pinned proxy image's own template).
# Mounted read-only over the image's haproxy.cfg.template; its stock
# entrypoint still renders ${BIND_CONFIG} from DISABLE_IPV6 at start.
# =============================================================================
"""

# Anchors in the upstream template. Each must occur exactly once.
FRONTEND_ANCHOR = "frontend dockerfrontend"
FINAL_DENY_ANCHOR = "    http-request deny"
DEFAULT_BACKEND_ANCHOR = "    default_backend dockerbackend"

# Inserted right after the frontend line, ahead of every upstream allow: the
# API may pull images, never name one itself.
IMAGE_NAMING_DENIES = (
    "    http-request deny if { method POST } { path,url_dec -m reg -i /images/(load|.+/tag)/*$ }",
    "    http-request deny if { method POST } { path,url_dec -m reg -i /images/create/*$ }"
    " !{ url_param(fromImage) -m reg . }",
    "    http-request deny if { method POST } { path,url_dec -m reg -i /images/create/*$ }"
    " { req.hdr(content-type) -m sub -i x-www-form-urlencoded }",
)

# Inserted right before the final catch-all deny.
CAPTURE_VOLUME_ALLOW = (
    "    http-request allow if { method GET DELETE }"
    " { path -m reg ^(/v[0-9.]+)?/volumes/syn-capture-[a-f0-9]{64}$ }"
)

# Inserted right after default_backend. Exec too: the guard and this proxy hold
# the socket, so one exec into either would bypass the create checks.
GUARD_ROUTES = (
    "    use_backend docker-create-guard if { method POST } { path,url_dec -m reg -i /containers/create/*$ }",
    "    use_backend docker-create-guard if { method POST } { path,url_dec -m reg -i /containers/.+/exec/*$ }",
)

# Appended at the end of the file.
GUARD_BACKEND = (
    "resolvers docker",
    "    parse-resolv-conf",
    "backend docker-create-guard",
    "    server guard docker-create-guard:2375 resolvers docker init-addr last,libc,none",
)


class TemplateAnchorError(ValueError):
    """The upstream template no longer has the shape this generator patches."""


@dataclass(frozen=True)
class ValidationFailure:
    step: str
    detail: str


def _single_index(lines: list[str], anchor: str) -> int:
    hits = [i for i, line in enumerate(lines) if line.rstrip() == anchor]
    if len(hits) != 1:
        raise TemplateAnchorError(
            f"expected exactly one line {anchor.strip()!r} in the upstream template, "
            f"found {len(hits)}; the proxy image changed shape, review the patch"
        )
    return hits[0]


def patch(upstream: str) -> str:
    """Return the upstream template with Syntropic137's rules inserted."""
    lines = upstream.splitlines()
    frontend = _single_index(lines, FRONTEND_ANCHOR)
    final_deny = _single_index(lines, FINAL_DENY_ANCHOR)
    default_backend = _single_index(lines, DEFAULT_BACKEND_ANCHOR)
    if not frontend < final_deny < default_backend:
        raise TemplateAnchorError(
            "expected frontend, then the final deny, then default_backend in the upstream template"
        )
    for line in (*IMAGE_NAMING_DENIES, CAPTURE_VOLUME_ALLOW, *GUARD_ROUTES, *GUARD_BACKEND):
        if line.strip() in (existing.strip() for existing in lines):
            raise TemplateAnchorError(f"upstream template already contains {line.strip()!r}")

    out: list[str] = []
    for i, line in enumerate(lines):
        if i == final_deny:
            out.append(CAPTURE_VOLUME_ALLOW)
        out.append(line)
        if i == frontend:
            out.extend(IMAGE_NAMING_DENIES)
        if i == default_backend:
            out.extend(GUARD_ROUTES)
    out.extend(GUARD_BACKEND)
    return HEADER + "\n".join(out) + "\n"


def generate() -> str:
    return patch(UPSTREAM_TEMPLATE.read_text())


def proxy_image() -> str:
    """The proxy image the base compose file pins, so validation tracks the pin."""
    services = yaml.safe_load(BASE_COMPOSE.read_text())["services"]
    return str(services["docker-socket-proxy"]["image"])


def _docker(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["docker", *args], capture_output=True, text=True, check=False)


def validate(image: str, generated: Path) -> list[ValidationFailure]:
    """Check the upstream copy against the image, then `haproxy -c` the output."""
    failures: list[ValidationFailure] = []
    pulled = _docker("pull", "--quiet", image)
    if pulled.returncode != 0:
        return [ValidationFailure("pull", pulled.stderr.strip())]

    upstream = _docker("run", "--rm", "--entrypoint", "cat", image, IMAGE_TEMPLATE_PATH)
    if upstream.returncode != 0:
        failures.append(ValidationFailure("read upstream template", upstream.stderr.strip()))
    elif upstream.stdout != UPSTREAM_TEMPLATE.read_text():
        failures.append(
            ValidationFailure(
                "upstream template",
                f"{UPSTREAM_TEMPLATE.relative_to(PROJECT_ROOT)} differs from {image}'s "
                f"{IMAGE_TEMPLATE_PATH}; refresh it from the image and regenerate",
            )
        )

    # The stock entrypoint renders the mounted template, then runs `haproxy -c`.
    checked = _docker(
        "run",
        "--rm",
        "-v",
        f"{generated}:{IMAGE_TEMPLATE_PATH}:ro",
        image,
        "haproxy",
        "-c",
        "-f",
        IMAGE_CONFIG_PATH,
    )
    if checked.returncode != 0:
        failures.append(ValidationFailure("haproxy -c", (checked.stdout + checked.stderr).strip()))
    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    mode.add_argument("--validate", action="store_true", help="validate with the proxy image")
    args = parser.parse_args(argv)

    rendered = generate()
    relative = OUTPUT_FILE.relative_to(PROJECT_ROOT)
    if args.check:
        if not OUTPUT_FILE.exists() or OUTPUT_FILE.read_text() != rendered:
            print(f"ERROR: {relative} is stale. Run: just gen-compose", file=sys.stderr)
            return 1
        print(f"OK: {OUTPUT_FILE.name} is up to date")
        return 0
    if args.validate:
        image = proxy_image()
        with tempfile.TemporaryDirectory() as tmp:
            generated = Path(tmp) / "haproxy.cfg.template"
            generated.write_text(rendered)
            generated.chmod(0o644)
            failures = validate(image, generated)
        for failure in failures:
            print(f"ERROR [{failure.step}]: {failure.detail}", file=sys.stderr)
        if failures:
            return 1
        print(f"OK: {relative} passes haproxy -c in {image}")
        return 0
    OUTPUT_FILE.write_text(rendered)
    print(f"Generated: {relative}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
